"""Named-entity political-probe runner (cases/political_probes/, split="probe").

Parallel to layer_b_political.py, but for the quarantined named-entity probe
tier: five cases, each in a NEU variant plus one or two named-disputed
variants (DIS, or DIS-A/DIS-B where two claimant framings exist). Records
are generated by generation/make_political_probes.py via verbatim anchor
replacement inside the scenario — within a pair, the user prompt differs by
exactly that swap (enforced by tests/test_political_probes_smoke.py).

Unlike Layer B, these variants DO name specific states and forces. Each
sample carries its case's disclaimer in metadata; the probe split is
excluded from the main benchmark and all reporting is descriptive and
per-case. The model under test is supplied the standard Inspect way
(`--model ...` on `inspect eval`); the task itself selects the variant
and condition:

    inspect eval inspect_eval/political_probes.py@political_probes \\
      --model openrouter/anthropic/claude-opus-4.8 \\
      -T variant=DIS-A -T condition=agent \\
      -T grader_model=openrouter/anthropic/claude-sonnet-4

Reporting discipline: TERTIARY at most, descriptive only, per-pair —
N=5 pairs is far too small for inference. The pre-registered primary
metric is unaffected by this tier.
"""

from __future__ import annotations

from pathlib import Path

from inspect_ai import Task, task
from inspect_ai.dataset import json_dataset

try:
    from inspect_eval.pilot_control_task import (
        _build_solver,
        escalation_level_match,
        human_authority_match,
        json_contract,
        record_to_sample,
    )
    from inspect_eval.scorers_graded import five_axis_graded
except ImportError:
    # `inspect eval path/to/file.py@task` loads this file as a top-level
    # module with its own directory on sys.path, not as a package member.
    from pilot_control_task import (
        _build_solver,
        escalation_level_match,
        human_authority_match,
        json_contract,
        record_to_sample,
    )
    from scorers_graded import five_axis_graded

PROBES_DIR = Path(__file__).resolve().parents[1] / "data" / "scenarios" / "political_probes"

VARIANT_IDS = ("NEU", "DIS", "DIS-A", "DIS-B")


@task
def political_probes(
    variant: str = "NEU",
    condition: str = "direct",
    grader_model: str | None = None,
) -> Task:
    """Run one variant file of the named-entity political probe.

    Args:
        variant: `NEU` (default), `DIS`, `DIS-A`, or `DIS-B` — selects
            data/scenarios/political_probes/<variant>.jsonl.
        condition: `direct` (default), `cot`, or `agent` — same solver
            chains as the main matrix (re-used via `_build_solver`).
        grader_model: grader for the 5-axis graded scorer (defaults to
            `anthropic/claude-sonnet-4`; must differ from the subject model).

    Every sample carries `metadata.political_probe_pair_id` and
    `metadata.political_probe_variant_id` (from the generated records) so
    the analysis notebook can join responses across variants of a pair.
    """
    if variant not in VARIANT_IDS:
        raise ValueError(f"variant must be one of: {', '.join(VARIANT_IDS)}")
    slug = variant.replace("-", "_").lower()
    condition_suffix = "" if condition == "direct" else f"_{condition}"
    return Task(
        dataset=json_dataset(str(PROBES_DIR / f"{variant}.jsonl"), sample_fields=record_to_sample),
        solver=_build_solver(condition),
        scorer=[
            json_contract(),
            escalation_level_match(),
            human_authority_match(),
            five_axis_graded(grader_model=grader_model),
        ],
        name=f"political_probes_{slug}{condition_suffix}",
        metadata={
            "benchmark": "Pilot Control",
            "layer": "political_probe_named",
            "variant": variant,
            "condition": condition,
            "split": "probe",
            "metric_tier": "tertiary",
            "reporting": "descriptive_only_per_pair",
        },
    )
